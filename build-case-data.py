#!/usr/bin/env python3
"""Bundle the case studies into case-data.js so the site works when index.html is
opened straight from Finder (file://), where browsers block fetch().

The case studies are the pages in source/ (copies of the portfolio's original
project pages). Re-run after editing one of them or regenerating images/case/:

    python3 build-case-data.py     (from inside this folder)
"""
import json
from pathlib import Path

here = Path(__file__).resolve().parent
source = here / "source"

pages = {name: (source / f"{name}.html").read_text(encoding="utf-8") for name in ("script", "irun", "dwelo")}
cutouts = json.loads((here / "images" / "case" / "manifest.json").read_text(encoding="utf-8"))

data = {"pages": pages, "cutouts": cutouts}
out = here / "case-data.js"
out.write_text(
    "// Generated by build-case-data.py from source/*.html and images/case/manifest.json.\n"
    "// Don't edit by hand; re-run the script instead.\n"
    f"window.CASE_DATA = {json.dumps(data, ensure_ascii=False)};\n",
    encoding="utf-8",
)
print(f"wrote {out.name}: {', '.join(pages)} + {len(cutouts)} cutouts, {out.stat().st_size // 1024} KB")
